import assert from 'node:assert/strict';
import {cpSync,existsSync,mkdirSync,readFileSync,realpathSync,writeFileSync,lstatSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import path from 'node:path';
const scratch='E:/Codex/tmp/encounter-expansion';
const stage=path.join(scratch,'native-final'),profile=path.join(scratch,'native-profile-final');
const build='E:/Codex/builds/nova-swarm/encounter-expansion/current';
const out='E:/Codex/builds/nova-swarm/encounter-expansion/evidence/desktop-smoke';
process.env.TEMP=process.env.TMP=scratch;process.env.NOVA_SWARM_ELECTRON_SMOKE_OUTPUT_DIR=out;
for(const directory of [scratch,stage,profile,out]){mkdirSync(directory,{recursive:true});
 assert(realpathSync(directory).toLowerCase().startsWith('e:\\codex\\'));assert(!lstatSync(directory).isSymbolicLink());}
assert(existsSync(path.join(build,'index.html')),'Build the E: candidate first');
assert.equal(realpathSync(build).toLowerCase(),path.resolve(build).toLowerCase(),'Build output must resolve to its approved E: path');
const quote=s=>`'${String(s).replaceAll("'","''")}'`;
const ownedStage=quote(stage.replaceAll('/','\\'));
const active=spawnSync('powershell.exe',['-NoProfile','-Command',`$owned=${ownedStage}; if(Get-CimInstance Win32_Process -Filter "Name='electron.exe'" | Where-Object {$_.CommandLine -and $_.CommandLine.Replace('/','\\').Contains($owned)}){exit 1}`],{encoding:'utf8'});
assert.equal(active.status,0,'A native test still owns this staging directory');
const marker=path.join(stage,'encounter-expansion-owned.txt');
assert(!existsSync(path.join(stage,'electron'))||existsSync(marker),'Unexplained staging is preserved');
writeFileSync(marker,'Disposable encounter-expansion native smoke staging; no production profile.\n');
const gate=spawnSync(process.execPath,['scripts/check-i18n.mjs'],{stdio:'inherit',env:process.env});assert.equal(gate.status,0);
cpSync(path.resolve('electron'),path.join(stage,'electron'),{recursive:true});
const main=path.join(stage,'electron/main.cjs');let code=readFileSync(main,'utf8');
const original="const distDir = path.resolve(__dirname, '..', 'dist');";
assert.equal(code.split(original).length,2,'Only the copied main entry is rebased');
code=code.replace(original,`const distDir = path.resolve(${JSON.stringify(build)});`);writeFileSync(main,code);
const executable=realpathSync(path.resolve('node_modules/electron/dist/electron.exe'));
const output=path.join(scratch,'native-out.log'),error=path.join(scratch,'native-error.log');
const argumentsList=[main.replaceAll('\\','/'),'--smoke','--nova-fresh-profile',`--nova-qa-user-data=${profile.replaceAll('\\','/')}`];
const command=`$p=Start-Process -FilePath ${quote(executable)} -ArgumentList @(${argumentsList.map(quote).join(',')}) -WindowStyle Hidden -RedirectStandardOutput ${quote(output)} -RedirectStandardError ${quote(error)} -Wait -PassThru; exit $p.ExitCode`;
const result=spawnSync('powershell.exe',['-NoProfile','-Command',command],{stdio:'inherit',env:process.env});assert.equal(result.status,0);
const report=JSON.parse(readFileSync(path.join(out,'report.json'),'utf8'));assert.equal(report.status,'passed');
assert(report.state.freshProfileSteamIsolated);console.log('PASS isolated E: native smoke; production Steam/profiles untouched');

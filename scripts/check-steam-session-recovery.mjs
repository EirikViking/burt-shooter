import assert from 'node:assert/strict';
globalThis.window={location:{origin:'http://127.0.0.1',search:''},localStorage:{getItem:()=>null,setItem(){}}};
const {LeaderboardAdapter}=await import('../src/leaderboard/LeaderboardAdapter.js');
const a=new LeaderboardAdapter();
let online=false,checks=0,finishFriends;
a.steamProvider.isAvailable=async()=>{checks++;return online;};
a.cloudProvider.isAvailable=async()=>true;
a.localProvider.isAvailable=async()=>true;
a.steamProvider.hasFriendLeaderboardEntries=()=>new Promise(resolve=>{finishFriends=resolve;});
a.retryPendingSteamSubmissions=async()=>({attempted:0});
a.retryPendingCareerRankMetadata=async()=>({attempted:0});
await a.refreshAvailability();assert.equal(a.isSteamAvailable(),false);
online=true;a.availabilityCheckedAt=Date.now()-4000;
const recovering=a.ensureAvailability();
await new Promise(resolve=>setImmediate(resolve));
assert.equal(a.isSteamAvailable(),true,'Steam must be ready before optional friends download');
assert.equal(a.shouldUseSteamSubmission(),true,'Game Over deadline must not redirect a Steam score locally');
assert.ok(a.getTabs().some(t=>t.id==='tactical'));
const joined=a.refreshAvailability();assert.equal(checks,2,'Concurrent recovery requests share a native check');
finishFriends(true);await recovering;await joined;assert.equal(a.availability.steamFriends,true);
online=false;await a.refreshAvailability();assert.equal(a.isSteamAvailable(),false);
assert.equal(a.availability.steamFriends,false);
await a.ensureAvailability();assert.equal(checks,3,'Offline checks are rate limited');
online=true;a.availabilityCheckedAt=Date.now()-4000;
const reconnect=a.ensureAvailability();await new Promise(resolve=>setImmediate(resolve));
finishFriends(false);await reconnect;
assert.equal(a.isSteamAvailable(),true,'Recover again after a later mid-session disconnection');
assert.equal(a.availability.steamFriends,false,'An empty friends board does not hide global boards');
console.log('PASS initial failure, mid-session reconnect, slow/empty friends, shared checks, retry throttling, Steam submission routing');

export function getModeBriefingReviewSourceText(locale) {
  if (locale === 'en') {
    return Object.freeze(Object.fromEntries(
      MODE_BRIEFING_SOURCE_TEXT.map((source) => [source, source])
    ));
  }
  const localized = TRANSLATIONS[locale];
  if (!localized || localized.length !== MODE_BRIEFING_SOURCE_TEXT.length) return {};
  return Object.freeze(Object.fromEntries(
    MODE_BRIEFING_SOURCE_TEXT.map((source, index) => [source, localized[index]])
  ));
}

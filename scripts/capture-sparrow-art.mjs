import { chromium } from 'playwright';
import fs from 'node:fs/promises';
const phase=process.argv[2]||'before';
const out=`output/playwright/ship-art-v2/${phase}`;
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',args:['--autoplay-policy=no-user-gesture-required']});
const context=await browser.newContext({viewport:{width:1920,height:1080},deviceScaleFactor:1});
const page=await context.newPage();const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:5199/?skipIntro=1&offlineLeaderboard=1&nova-devtools-hash=f07e7cbbaa835bfa3ecf9bb181e93e59a8f86021ddcda00ec835edcad56a559c');
await page.waitForFunction(()=>window.__game?.scenes?.menu?.astraMenuShip?.ready,{},{timeout:90000});
await page.waitForTimeout(2000);
await page.screenshot({path:`${out}/menu.png`});
const menu=await page.evaluate(()=>{const t=window.__game.scenes.menu.astraMenuShip;return {index:t.index,angle:t.viewAngle,pitch:t.pitch,size:t.solid.size};});
await page.evaluate(()=>window.__game.showShipSelect());
await page.waitForFunction(()=>window.__game.scenes.shipSelect.rotatingCard?.turntable?.ready,{},{timeout:60000});
await page.waitForTimeout(1200);await page.screenshot({path:`${out}/hangar.png`});
const hangar=await page.evaluate(()=>JSON.parse(window.render_game_to_text()));
await page.evaluate(()=>window.__game.startGame(window.__game.selectedShipSpriteKey));
await page.waitForFunction(()=>window.__game.currentSceneName==='play',{},{timeout:60000});
await page.keyboard.down('Space');await page.keyboard.down('ArrowLeft');await page.waitForTimeout(300);await page.keyboard.up('ArrowLeft');
await page.keyboard.down('ArrowRight');await page.waitForTimeout(300);await page.keyboard.up('ArrowRight');
await page.waitForTimeout(12000);await page.screenshot({path:`${out}/gameplay.png`});await page.keyboard.up('Space');
const gameplay=await page.evaluate(()=>JSON.parse(window.render_game_to_text()));
await fs.writeFile(`${out}/capture.json`,JSON.stringify({phase,menu,hangar,gameplay,errors},null,2));
await browser.close();console.log(JSON.stringify({phase,menu,errors}));

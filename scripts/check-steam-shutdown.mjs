import assert from 'node:assert/strict';
import fs from 'node:fs';import vm from 'node:vm';
const source=fs.readFileSync('node_modules/steamworks-ffi-node/dist/internal/SteamCallbackPoller.js','utf8');
let active=true,nativeCalls=0;
const exports={};
vm.runInNewContext(source,{exports,console,setTimeout:resolve=>{active=false;resolve();},require:()=>({})});
const api={getUtilsInterface:()=>1,isInitialized:()=>active,runCallbacks:()=>nativeCalls++};
const loader=new Proxy({},{get:()=>()=>{nativeCalls++;throw Error('Native call after shutdown');}});
const poller=new exports.SteamCallbackPoller(loader,api);
assert.equal(await poller.poll(1,{},1104),null);
assert.equal(nativeCalls,0);
console.log('PASS pending Steam poll cancels before any native call after shutdown.');
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {createSteamLeaderboardBridge}=require('../electron/steamLeaderboardBridge.cjs');
const bridge=createSteamLeaderboardBridge({allowNativeLoad:false});
let shutdowns=0;
bridge.initialized=true;
bridge.steam={shutdown(){shutdowns++;},leaderboards:{apiCore:{getUtilsInterface:()=>1,isInitialized:()=>true,runCallbacks:()=>assert.fail('callback after shutdown')},libraryLoader:{SteamAPI_ISteamUtils_IsAPICallCompleted:()=>assert.fail('poll after shutdown'),SteamAPI_ISteamUtils_GetAPICallResult:()=>assert.fail('result after shutdown')}}};
const pending=bridge.pollApiCallResultDetailed({callHandle:1,resultStruct:{},callbackId:1106,delayMs:1});
bridge.shutdown();bridge.shutdown();
assert.equal((await pending).reason,'shutdown');
assert.equal(shutdowns,1);
assert.equal(await bridge.initialize(),false,'shutdown must not reinitialize Steam in a late continuation');
console.log('PASS bridge cancels pending diagnostic/upload polling without acceptance and shuts down exactly once.');

const screenshotBridge=createSteamLeaderboardBridge({allowNativeLoad:false});
let finishCapture;
screenshotBridge.initialized=true;
screenshotBridge.steam={shutdown(){},screenshots:{addScreenshotToLibrary:()=>assert.fail('screenshot native call after quit')}};
const capture=screenshotBridge.captureElectronScreenshot({isDestroyed:()=>false,webContents:{capturePage:()=>new Promise(resolve=>finishCapture=resolve)}});
screenshotBridge.shutdown();finishCapture({getSize:()=>assert.fail('cancel capture before file work')});
assert.equal((await capture).reason,'shutdown');
console.log('PASS an in-flight F12 capture cannot call the Steam SDK after shutdown.');

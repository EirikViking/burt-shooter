import assert from 'node:assert/strict';
import { planBossDiscovery } from '../src/config/DiscoveryProgression.js';

const relay = planBossDiscovery(31, 'threshold-fixture', { roll: .14 });
const relaySnake = planBossDiscovery(31, 'threshold-fixture', { roll: .22 });
const snake = planBossDiscovery(31, 'threshold-fixture', { roll: .04 });
assert.equal(relay.kind, 'relay');
assert.equal(relaySnake.kind, 'relay_snake');
assert.equal(relay.threshold, .30, 'second boss keeps the original 30% primary-health gate');
assert.equal(relaySnake.threshold, .30, 'second boss in relay-snake keeps the same gate');
assert.equal(snake.threshold, .65, 'snake encounter retains its own threshold');

globalThis.Audio = class { addEventListener() {} };
const { BossDiscoveryEncounter } = await import('../src/managers/BossDiscoveryEncounter.js');
const primary = { active: true, health: 40, maxHealth: 100 };
const encounter = Object.create(BossDiscoveryEncounter.prototype);
encounter.plan = relay;
encounter.stage = 'waiting';
encounter.age = 0;
encounter.immediateReinforcement = false;
encounter.primary = primary;
encounter.lastLives = 3;
encounter.manager = { game: { lives: 3, getWidth: () => 1280, scenes: { play: {} } } };
encounter.announce = () => {};
encounter.update(1);
assert.equal(encounter.stage, 'waiting', 'guest must not announce at 40% primary health');
primary.health = 29;
encounter.update(1);
assert.equal(encounter.stage, 'warning', 'guest announces only below 30% primary health');
assert.ok(encounter.releaseAt > encounter.age, 'warning precedes actual arrival');
encounter.stage = 'loading';
encounter.releaseAt = encounter.age;
encounter.readyGuest = { active: true };
let arrivals = 0;
encounter.attachGuest = () => { arrivals++; encounter.readyGuest = null; encounter.stage = 'active'; };
primary.attackWarningToken = { id: 'announced_lane' };
encounter.update(1);
assert.equal(arrivals, 0, 'guest must wait for the primary attack warning to finish');
assert.equal(primary.discoveryLane, null, 'the warned primary lane must stay put');
primary.attackWarningToken = null;
encounter.update(1);
assert.equal(arrivals, 1, 'guest arrives after the warned attack');
console.log('[boss-guest-arrival] PASS relay 30% gate, warning delay, snake isolation');

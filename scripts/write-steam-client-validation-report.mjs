import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const templatePath = path.resolve(root, 'release/steamworks/client_validation_report.template.json');
const versionPath = path.resolve(root, 'public/version.json');
const outputPath = path.resolve(process.env.STEAM_CLIENT_VALIDATION_OUTPUT || 'release/steamworks/client_validation_report.json');
const confirmText = 'I_REVIEWED_STEAM_CLIENT_BUILD';
const allChecksText = 'YES';

function requiredEnv(name) {
  const value = (process.env[name] || '').trim();
  if (!value) throw new Error(`${name} is required.`);
  return value;
}

function fileInfoFromEnv(name) {
  const raw = requiredEnv(name);
  const full = path.resolve(root, raw);
  if (!existsSync(full)) throw new Error(`${name} must point to an existing evidence file: ${raw}`);
  const stats = statSync(full);
  if (!stats.isFile() || stats.size <= 0) throw new Error(`${name} must point to a non-empty evidence file: ${raw}`);
  return path.relative(root, full).replaceAll(path.sep, '/');
}

function parseNotes(value) {
  return String(value || '')
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);
}

if (!existsSync(templatePath)) {
  throw new Error(`Missing validation template: ${path.relative(root, templatePath).replaceAll(path.sep, '/')}`);
}

if (!existsSync(versionPath)) {
  throw new Error('Missing public/version.json; build metadata is required for Steam-client validation evidence.');
}

if ((process.env.STEAM_CLIENT_VALIDATION_CONFIRM || '').trim() !== confirmText) {
  throw new Error(`Set STEAM_CLIENT_VALIDATION_CONFIRM=${confirmText} after testing the real Steam-installed build.`);
}

if ((process.env.STEAM_CLIENT_ALL_CHECKS_PASSED || '').trim().toUpperCase() !== allChecksText) {
  throw new Error(`Set STEAM_CLIENT_ALL_CHECKS_PASSED=${allChecksText} only after every required Steam-client check passes.`);
}

const steamBuildId = requiredEnv('STEAM_BUILD_ID');
const validatedBy = requiredEnv('STEAM_VALIDATED_BY');
const installPath = requiredEnv('STEAM_INSTALL_PATH');
const resolvedInstallPath = path.resolve(installPath);
if (!existsSync(resolvedInstallPath)) {
  throw new Error(`STEAM_INSTALL_PATH must exist on this machine: ${installPath}`);
}

const screenshotEvidence = fileInfoFromEnv('STEAM_SCREENSHOT_EVIDENCE');
const template = JSON.parse(readFileSync(templatePath, 'utf8'));
const version = JSON.parse(readFileSync(versionPath, 'utf8'));
const checks = Object.fromEntries(Object.keys(template.checks || {}).map((key) => [key, true]));
const report = {
  ...template,
  status: 'passed',
  gameBuild: {
    version: version.version || null,
    timestamp: version.timestamp || null
  },
  steamBuildId,
  validatedAt: new Date().toISOString(),
  validatedBy,
  steamInstallPath: installPath,
  screenshotEvidence,
  checks,
  notes: [
    'Generated by npm run steamworks:write-client-validation after explicit real Steam-client validation confirmation.',
    'This report must only be kept if the build was installed and launched through Steam, not from the local unpacked folder.',
    ...parseNotes(process.env.STEAM_CLIENT_VALIDATION_NOTES)
  ]
};

const missing = Object.entries(report.checks).filter(([, passed]) => passed !== true).map(([key]) => key);
if (report.status !== 'passed' || missing.length) {
  throw new Error(`Refusing to write non-passing validation report; missing checks: ${missing.join(', ') || 'unknown'}`);
}

mkdirSync(path.dirname(outputPath), { recursive: true });
writeFileSync(outputPath, `${JSON.stringify(report, null, 2)}\n`, 'utf8');
console.log(`wrote ${path.relative(root, outputPath).replaceAll(path.sep, '/')}`);

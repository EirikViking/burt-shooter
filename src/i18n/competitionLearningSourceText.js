export function getCompetitionLearningSourceText(locale = 'en') {
  const localized = TRANSLATIONS[locale];
  if (!localized) return Object.freeze({});
  if (localized.length !== SOURCE.length) {
    throw new Error(`Competition learning translation count mismatch for ${locale}: ${localized.length}/${SOURCE.length}`);
  }
  return Object.freeze(Object.fromEntries(SOURCE.map((source, index) => [source, localized[index]])));
}

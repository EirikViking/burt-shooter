import assert from 'node:assert/strict';
import { FirstLightModel, firstLightEncounterForSector, firstLightEligible, firstLightRivalDroneValue } from '../src/game/ArcadeFirstLight.js';

for (const mode of ['ranked', 'ranked_tactical', 'overrun_pure', 'overrun_tactical', 'scout', 'sector_start']) {
  assert.equal(firstLightEligible({ runMode: mode }), true, mode);
}
for (const mode of ['daily_signal', 'unranked', 'unknown']) assert.equal(firstLightEligible({ runMode: mode }), false);
assert.equal(firstLightEligible({ runMode: 'ranked', lateGameExperiment: { active: true } }), false);
assert.equal(firstLightEncounterForSector(1), 'convoy');
assert.equal(firstLightEncounterForSector(2), 'rival');
assert.equal(firstLightEncounterForSector(51), 'convoy');
assert.equal(firstLightEncounterForSector(52), 'rival');
assert(firstLightRivalDroneValue(2,5)>firstLightRivalDroneValue(2,0), 'different rivals carry different score values');
assert(firstLightRivalDroneValue(12,0)>firstLightRivalDroneValue(2,0), 'later sectors increase the value');
assert(firstLightRivalDroneValue(52,0)>firstLightRivalDroneValue(12,0), 'value continues to rise in late play');
assert(firstLightRivalDroneValue(52,5)<=50000, 'reward is bounded');
for (const level of [3, 4, 10, 50, 53]) assert.equal(firstLightEncounterForSector(level), null);
const model = new FirstLightModel('test-seed');
for (let i = 0; i < 80; i++) model.update(.1, { sector: 1, safe: false });
assert.equal(model.encounter, null, 'unsafe combat never advances admission');
for (let i = 0; i < 52; i++) model.update(.1, { sector: 1, safe: true });
assert.equal(model.encounter.kind, 'convoy');
const bullet = {};
assert.equal(model.hit('left', 100, bullet).type, 'rescue');
assert.equal(model.hit('right', 100, bullet), null, 'one projectile cannot farm multiple clamps');
assert.equal(model.hit('left', 100, {}), null, 'freed fighter cannot be reclaimed');
assert.equal(model.hit('right', 100, {}).type, 'rescue');
assert.equal(model.escorts.length, 2);
assert(model.encounter.duration - model.encounter.age >= 3, 'completed rescue needs a visible launch and powered exit');
const before = model.encounter.age;
model.update(5, { sector: 1, safe: true, paused: true });
assert.equal(model.encounter.age, before, 'pause freezes choreography and support');
for (let i = 0; i < 150; i++) model.update(.1, { sector: 1, safe: true });
assert.equal(model.encounter, null); assert.equal(model.escorts.length, 0);
for (let i = 0; i < 80; i++) model.update(.1, { sector: 1, safe: true });
assert.equal(model.encounter, null, 'once per eligible sector');
for (let i = 0; i < 42; i++) model.update(.1, { sector: 2, safe: true });
assert.equal(model.encounter.kind, 'rival');
assert.equal(model.hit('core', 100, {}), null, 'core armored while either gun survives');
assert.equal(model.hit('left', 100, {}).type, 'weapon');
assert.equal(model.attackEnabled('left'), false); assert.equal(model.attackEnabled('right'), true);
assert.equal(model.hit('core', 100, {}), null);
assert.equal(model.hit('right', 100, {}).type, 'weapon');
assert.equal(model.hit('core', NaN, {}), null);
assert.equal(model.hit('core', 100, {}).type, 'victory');
assert.equal(model.hit('core', 100, {}), null, 'single reward claim');
model.cancel('death'); assert.equal(model.encounter, null); assert.equal(model.escorts.length, 0);
for (let i = 0; i < 60; i++) model.update(.1, { sector: 51, safe: true });
assert.equal(model.encounter.kind, 'convoy', 'recurs in later Onslaught sectors');
model.update(.1, { sector: 52, safe: false });
assert.equal(model.encounter.kind, 'convoy', 'a transition preserves an unfinished rescue');
assert.equal(model.encounter.suspended, true, 'an incompatible phase pauses the encounter');
const twin = new FirstLightModel('test-seed');
assert.equal(twin.variantFor(52), model.variantFor(52), 'deterministic independent selection');
const timeout = new FirstLightModel('timeout');
for (let i = 0; i < 260; i++) timeout.update(.1, { sector: 2, safe: true });
assert.equal(timeout.encounter, null, 'missed rival expires without wave gate or reward');
assert.equal(timeout.rewardCount, 0);
console.log('[arcade-first-light] PASS mode scope, recurring cadence, safe admission, rescue, module order, projectile deduplication, pause, expiration and one-time reward');
